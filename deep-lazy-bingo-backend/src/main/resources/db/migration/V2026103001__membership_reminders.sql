CREATE TABLE bingo_membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL CHECK (owner_id > 0),
    CONSTRAINT bingo_membership_owner_identity UNIQUE (id, owner_id)
);

CREATE TABLE bingo_membership_reminder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    expires_on DATE NOT NULL,
    recipient VARCHAR(254),
    body VARCHAR(8192) NOT NULL,
    status VARCHAR(32) DEFAULT 'PENDING' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT bingo_reminder_membership_owner FOREIGN KEY (membership_id, owner_id)
        REFERENCES bingo_membership (id, owner_id),
    CONSTRAINT bingo_reminder_expiry_cycle UNIQUE (owner_id, membership_id, expires_on),
    CONSTRAINT bingo_reminder_status CHECK
        (status IN ('PENDING', 'CLAIMED', 'SMTP_ACCEPTED', 'FAILED', 'INVALID_RECIPIENT'))
);

CREATE INDEX bingo_reminder_due_idx ON bingo_membership_reminder (status, expires_on, id);